    data class RawStation(val name: String, val lat: Double, val lon: Double)

    data class LineSeed(
        val meta: LineMeta,
        val stations: List<Station>,
        /** null = LINEAR(order 인접). non-null = BRANCHED 명시 엣지(statnId 쌍). */
        val edges: List<Pair<String, String>>? = null,
    )

    fun edgesFor(lineId: String): List<Pair<String, String>>? =
        allLines.firstOrNull { it.meta.lineId == lineId }?.edges


    private const val NOMINAL_SEC = 120

    private fun buildLine(
        lineId: String,
        lineName: String,
        ascendingUpdnLine: String,
        statnIdBase: Int,
        raws: List<RawStation>,
        displayName: String = lineName,
        excludedTerminusNames: Set<String> = emptySet(),
    ): LineSeed {
        fun statnId(order: Int): String = "%s%06d".format(lineId, statnIdBase + order)
        val stations = raws.mapIndexed { i, raw ->
            Station(
                statnId = statnId(i),
                lineId = lineId,
                name = raw.name,
                order = i,
                avgSecToNext = if (i == raws.lastIndex) 0 else NOMINAL_SEC,
                nextStatnId = if (i == raws.lastIndex) null else statnId(i + 1),
                prevStatnId = if (i == 0) null else statnId(i - 1),
                lat = raw.lat,
                lon = raw.lon,
            )
        }
        val meta = LineMeta(
            lineId = lineId,
            lineName = lineName,
            supportsRealtime = true,
            topology = LineTopology.LINEAR,
            directionPolarity = DirectionPolarity(ascendingUpdnLine),
            displayName = displayName,
            excludedTerminusNames = excludedTerminusNames,
        )
        return LineSeed(meta, stations)
    }

